// Regression: an unrated keeper must not become a measured zero or a false tie.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname,'../src/web_template.html'),'utf8');
const from = source.indexOf('function matchComparisonBasis(');
const to = source.indexOf('\nfunction sokeTable(',from);
assert.ok(from>=0 && to>from);
const context={ov:p=>['KT','CH','DD','PN','TC','TL','DN','TD'].reduce((s,k)=>s+p[k],0)/8}; vm.runInNewContext(source.slice(from,to),context);
const p=v=>Object.fromEntries(['KT','CH','DD','PN','TC','TL','DN','TD'].map(k=>[k,v]));
const sel=[p(6),p(6),p(6),p(6),p(6),p(6),p(6),p(5),p(4)];
const A={starters:[0,1,2,3,4,5,6],bench:[7],startFit:42,gkFit:6,total:47};
const B={starters:[0,1,2,3,4,5,6],bench:[8,7],startFit:44,gkFit:8,total:53};
const old=context.matchComparisonBasis(A,B,sel);
assert.equal(old.incompleteGk,false);
assert.equal(old.startA,42); assert.equal(old.startB,44);
assert.equal(old.totalA,47); assert.equal(old.totalB,53);
const unknown=context.matchComparisonBasis({...A,gkRated:false,startFit:36,gkFit:0,total:41},B,sel);
assert.equal(unknown.incompleteGk,true);
assert.equal(unknown.startA,36); assert.equal(unknown.startB,36);
assert.equal(unknown.benchCount,1);
assert.equal(unknown.benchA,5); assert.equal(unknown.benchB,5);
assert.equal(unknown.totalA,41); assert.equal(unknown.totalB,41);
assert.equal(unknown.outfieldCount,6);
const none=context.matchComparisonBasis({...A,gkRated:false,bench:[]},B,sel);
assert.equal(none.benchCount,0); assert.equal(none.benchA,0); assert.equal(none.benchB,0);
assert.ok(source.includes('A.gkRated===false?"Chưa chấm"'));
assert.ok(source.includes('if(comparable){if(aw)_aW++'));
console.log('Known-keeper matches unchanged; unrated keeper and extra bench comparison: OK');
